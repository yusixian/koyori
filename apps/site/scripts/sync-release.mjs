import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(siteRoot, "../../docs/releases/unreleased.md");
const targetPath = resolve(siteRoot, "app/generated/release.ts");
const fallback = [
  "## 当前阶段",
  "",
  "Koyori 正在建立首版工程、公开文档与发布基线。",
  "",
  "- 尚无已发布安装包。",
  "- 尚无 GitHub Release 或稳定更新通道。",
  "- 已验证能力会随工程进展补充到公开文档。",
].join("\n");

let markdown = fallback;
let sourceFound = false;

try {
  markdown = await readFile(sourcePath, "utf8");
  sourceFound = true;
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

markdown = markdown.replace(/^---\s*\n[\s\S]*?\n---\s*\n?/, "").trim();
const moduleSource = [
  "// Generated by scripts/sync-release.mjs. Do not edit by hand.",
  `export const releaseSourceFound = ${sourceFound};`,
  `export const releaseMarkdown = ${JSON.stringify(markdown)};`,
  "",
].join("\n");

await mkdir(dirname(targetPath), { recursive: true });
await writeFile(targetPath, moduleSource, "utf8");
